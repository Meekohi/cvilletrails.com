import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright');
const browser=await chromium.launch({headless:true,executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE,args:['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
try {
 const page=await browser.newPage({viewport:{width:1500,height:1000}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8009/',{waitUntil:'networkidle'});
 await page.waitForFunction(()=>window.__batchMap?.loaded()&&window.__batchMap.getLayer('candidate-lines'));
 const report=await page.evaluate(()=>window.__batchReport);
 assert.equal(await page.locator('#parks option').count(),report.parks.length+1);
 assert.ok(report.counts.candidate>400);
 assert.equal(await page.locator('#parks').inputValue(),'');
 assert.equal(await page.evaluate(()=>window.__batchMap.getLayoutProperty('held-lines','visibility')),'none');
 await page.screenshot({path:'test-results/state-parks-batch-overview.png'});
 const park='Bear Creek Lake State Park',parkCount=report.parks.find(p=>p.name===park).counts.candidate;
 const marker=await page.evaluate(name=>{const f=window.__batchMap.getSource('park-centers')._data.features.find(f=>f.properties.name===name);const p=window.__batchMap.project(f.geometry.coordinates);return {x:p.x,y:p.y}},park);
 await page.mouse.click(marker.x,marker.y);
 await page.waitForFunction(name=>document.getElementById('parks').value===name,park);
 await page.waitForFunction(()=>window.__batchMap.loaded());
 const ids=await page.evaluate(()=>[...new Set(window.__batchMap.queryRenderedFeatures({layers:['candidate-lines']}).map(f=>f.properties.review_id))]);
 assert.equal(ids.length,parkCount);
 await page.screenshot({path:'test-results/state-parks-batch-bear-creek.png'});
 await page.locator('#candidate').uncheck();
 assert.equal(await page.evaluate(()=>window.__batchMap.getLayoutProperty('candidate-lines','visibility')),'none');
 await page.locator('#candidate').check();await page.locator('#held').check();
 assert.equal(await page.evaluate(()=>window.__batchMap.getLayoutProperty('held-lines','visibility')),'visible');
 await page.locator('#accept').click();await page.locator('#skip-park').click();
 await page.locator('#parks').selectOption('Caledon State Park');
 await page.locator('#rows button').filter({hasText:/^Exclude trail$/}).first().click();
 await page.locator('#notes').fill('Sanity check: browser-test exclusions.');
 const pending=page.waitForEvent('download');await page.locator('#export').click();
 const download=await pending,exported=JSON.parse(await readFile(await download.path(),'utf8'));
 assert.equal(exported.kind,'virginia-state-parks-batch');
 assert.equal(exported.decision,'accept');assert.equal(exported.plan_hash,report.plan_hash);assert.equal(exported.review_hash,report.review_hash);
 assert.deepEqual(exported.excluded_parks,[park]);assert.equal(exported.excluded_features.length,1);
 assert.equal(exported.included_count,report.counts.candidate-parkCount-1);
 const candidateIds=new Set(report.parks.flatMap(p=>p.rows.filter(r=>r.category==='candidate').map(r=>r.id)));
 assert.ok(exported.included_feature_ids.every(id=>candidateIds.has(id)));
 assert.ok(!exported.included_feature_ids.includes(exported.excluded_features[0]));
 await page.reload({waitUntil:'networkidle'});await page.waitForFunction(()=>window.__batchMap?.loaded()&&window.__batchMap.getLayer('candidate-lines'));
 assert.match(await page.locator('#state').textContent(),/Accepted/);assert.equal(await page.locator('#notes').inputValue(),exported.notes);
 await page.locator('#parks').selectOption('Leesylvania State Park');await page.locator('#exceptions').check();
 assert.match(await page.locator('#rows').textContent(),/closed or abandoned trail name/);
 await page.setViewportSize({width:390,height:844});await page.locator('#overview').click();
 const rect=await page.locator('aside').boundingBox();assert.ok(rect.x>=0&&rect.width<390&&rect.height<844*.5);
 await page.screenshot({path:'test-results/state-parks-batch-mobile.png'});
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({candidate:report.counts.candidate,held:report.counts.held,parks:report.candidate_park_count,checks:'overview, rendered park, toggles, batch acceptance, park/trail exclusions, hash-bound export, persistence, closed-name exception, mobile layout',passed:true}));
} finally {await browser.close()}
