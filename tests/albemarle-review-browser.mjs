import assert from 'node:assert/strict';
import {mkdir, readFile} from 'node:fs/promises';
const {chromium} = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE,
  args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader']});
try {
  await mkdir('test-results', {recursive: true});
  const page = await browser.newPage({viewport: {width: 1500, height: 1000}}), errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(process.env.ALBEMARLE_REVIEW_URL || 'http://127.0.0.1:8010/', {waitUntil: 'networkidle'});
  await page.waitForFunction(() => window.__albemarleReady && window.__albemarleMap.loaded());
  const report = await page.evaluate(() => window.__albemarleReport);
  assert.equal(report.publication_authorized, false);
  assert.equal(report.counts.existing_preserved, 350);
  assert.ok(report.counts.held > report.counts.eligible);
  assert.equal(await page.locator('#parks option').count(), report.parks.length + 1);
  await page.screenshot({path: 'test-results/albemarle-overview.png'});
  await page.locator('#parks').selectOption('ivy-creek-natural-area');
  await page.waitForFunction(() => window.__albemarleMap.loaded());
  const rendered = await page.evaluate(() => [...new Set(window.__albemarleMap.queryRenderedFeatures({layers: ['eligible-lines']}).map(f => f.properties.review_id))]);
  assert.equal(rendered.length, report.parks.find(p => p.id === 'ivy-creek-natural-area').source_counts.eligible);
  await page.locator('#filter').selectOption('eligible');
  await page.locator('#search').fill('Brown Connector');
  await page.locator('#rows button').first().click();
  assert.match(await page.locator('#detail').textContent(), /rendered_color/);
  assert.match(await page.locator('#detail').textContent(), /source covered:.*current covered:/);
  await page.locator('#colors').check();
  assert.deepEqual(await page.evaluate(() => window.__albemarleMap.getPaintProperty('eligible-lines', 'line-color')), ['get', 'review_color']);
  await page.locator('#feature-decision').selectOption('investigate');
  await page.locator('#feature-notes').fill('Check connector naming and retain the established color.');
  await page.screenshot({path: 'test-results/albemarle-ivy-color-conflict.png'});
  await page.locator('#parks').selectOption('ragged-mountain');
  await page.locator('#search').fill('');
  await page.locator('#filter').selectOption('existing');
  assert.equal(await page.locator('#rows button').count(), 22);
  await page.locator('#rows button').first().click();
  assert.match(await page.locator('#detail').textContent(), /0\.0% \/ 0\.0%/);
  await page.locator('#park-decision').selectOption('keep-existing');
  await page.locator('#park-notes').fill('No eligible replacement for the current Ragged network.');
  await page.locator('#held').check();
  assert.equal(await page.evaluate(() => window.__albemarleMap.getLayoutProperty('held-lines', 'visibility')), 'visible');
  await page.screenshot({path: 'test-results/albemarle-ragged-held.png'});
  await page.locator('#parks').selectOption('biscuit-run');
  await page.locator('#filter').selectOption('held');
  assert.ok(await page.locator('#rows button').count() > 0);
  await page.locator('#eligible').uncheck();
  assert.equal(await page.evaluate(() => window.__albemarleMap.getLayoutProperty('eligible-lines', 'visibility')), 'none');
  await page.locator('#eligible').check();
  await page.locator('#notes').fill('Browser validation: feedback only; no publication approval.');
  const pending = page.waitForEvent('download');
  await page.locator('#export').click();
  const downloaded = await pending;
  const exported = JSON.parse(await readFile(await downloaded.path(), 'utf8'));
  assert.equal(exported.review_hash, report.review_hash);
  assert.equal(exported.source_hash, report.source_hash);
  assert.equal(exported.baseline_hash, report.baseline_hash);
  assert.equal(exported.publication_authorized, false);
  assert.equal(exported.parks['ragged-mountain'].decision, 'keep-existing');
  assert.equal(Object.values(exported.features)[0].decision, 'investigate');
  await page.reload({waitUntil: 'networkidle'});
  await page.waitForFunction(() => window.__albemarleReady && window.__albemarleMap.loaded());
  assert.equal(await page.locator('#notes').inputValue(), exported.notes);
  await page.locator('#parks').selectOption('ragged-mountain');
  assert.equal(await page.locator('#park-decision').inputValue(), 'keep-existing');
  await page.setViewportSize({width: 390, height: 844});
  await page.locator('#overview').click();
  const rect = await page.locator('aside').boundingBox();
  assert.ok(rect.width < 390 && rect.height < 844 * .5);
  await page.screenshot({path: 'test-results/albemarle-mobile.png'});
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({passed: true, counts: report.counts,
    checks: 'saved overlays render, eligible/held toggles, color conflicts, reverse coverage, protected-current feedback, hash-bound export, persistence, mobile layout'}));
} finally {
  await browser.close();
}
