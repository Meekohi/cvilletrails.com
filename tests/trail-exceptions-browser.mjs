import assert from 'node:assert/strict';
import {mkdir,readFile} from 'node:fs/promises';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright');
const browser=await chromium.launch({headless:true,executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE,args:['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
try{
  const page=await browser.newPage({viewport:{width:1500,height:1000}}),errors=[];
  page.on('pageerror',(e)=>errors.push(e.message));
  await page.goto('http://127.0.0.1:8011/exceptions/',{waitUntil:'networkidle'});
  await page.waitForFunction(()=>window.exceptionReviewReady);
  await page.waitForFunction(()=>window.exceptionMaps.every((m)=>m.loaded())&&window.exceptionMaps[1].queryRenderedFeatures({layers:['selected-incoming']}).length>0,null,{timeout:60000});
  assert.equal(await page.locator('#category').inputValue(),'access');
  assert.match(await page.locator('#count').textContent(),/12 records/);
  assert.match(await page.locator('#summary').textContent(),/139 approved, 17 rejected, 12 held/);
  assert.equal(await page.locator('#decision').count(),0);
  await page.locator('#outcome').selectOption('approve');
  assert.match(await page.locator('#count').textContent(),/139 records/);
  await page.locator('#outcome').selectOption('reject');
  assert.match(await page.locator('#count').textContent(),/17 records/);
  await page.locator('#category').selectOption('appalachian');
  assert.match(await page.locator('#count').textContent(),/73 records/);
  assert.ok(await page.evaluate(()=>window.exceptionMaps[0].queryRenderedFeatures({layers:['official-at']}).length>0));
  await mkdir('test-results',{recursive:true});
  await page.screenshot({path:'test-results/trail-exceptions-at.png'});
  assert.ok(await page.locator('#decision').isDisabled());
  assert.match(await page.locator('#count').textContent(),/73 choices recorded/);
  await page.locator('#official').uncheck();
  assert.deepEqual(await page.evaluate(()=>window.exceptionMaps[0].getFilter('official-at')[2]),['literal',[]]);
  await page.locator('#category').selectOption('state-parks');
  assert.match(await page.locator('#detail').textContent(),/official Virginia DCR GIS/);
  assert.ok(await page.locator('#decision').isDisabled());
  await page.locator('#category').selectOption('patc');
  assert.match(await page.locator('#detail').textContent(),/differential-GPS survey/);
  await page.waitForFunction(()=>window.exceptionMaps.every((m)=>m.loaded())&&window.exceptionMaps[1].queryRenderedFeatures({layers:['selected-incoming']}).length>0,null,{timeout:60000});
  await page.screenshot({path:'test-results/trail-exceptions-patc.png'});
  assert.ok(await page.locator('#decision').isDisabled());
  await page.locator('#category').selectOption('access');assert.equal(await page.locator('#decision').count(),0);
  await page.locator('#category').selectOption('resolved');assert.equal(await page.locator('#decision').count(),0);assert.match(await page.locator('#detail').textContent(),/already accepted/);
  const pending=page.waitForEvent('download');await page.locator('#export').click();const download=await pending;
  const value=JSON.parse(await readFile(await download.path(),'utf8'));
  assert.equal(value.kind,'tnc-usfs-source-exceptions');assert.equal(Object.keys(value.decisions).length,305);
  assert.equal(Object.values(value.decisions).filter((x)=>x==='official-at').length,73);
  assert.ok(!('usfs-gwj:4ed9a77a-95c3-41d5-a151-9b669ea61696' in value.decisions));
  for(const key of ['acceptance_hash','confirmed_hash','access_hash'])assert.match(value[key],/^[0-9a-f]{64}$/);
  await download.saveAs('test-results/trail-exception-test-feedback.json');
  await page.reload({waitUntil:'networkidle'});await page.waitForFunction(()=>window.exceptionReviewReady);assert.match(await page.locator('#count').textContent(),/12 records/);
  await page.setViewportSize({width:390,height:844});await page.locator('#fit').click();
  await page.waitForFunction(()=>window.exceptionMaps.every((m)=>m.loaded()),null,{timeout:60000});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
  await page.screenshot({path:'test-results/trail-exceptions-mobile.png'});
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({passed:true,unresolved:305,checks:'rendered official and incoming lines, authority explanations, confirmed choices locked, access outcomes, frozen Sandy Gap, hash-bound export, persistence, mobile'}));
}finally{await browser.close();}
