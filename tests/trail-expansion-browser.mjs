import assert from 'node:assert/strict';
import {readFile,mkdir} from 'node:fs/promises';
const {chromium} = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({headless:true,executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE,args:['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
try {
  const page = await browser.newPage({viewport:{width:1500,height:1000}}), errors=[];
  page.on('pageerror',(e) => errors.push(e.message));
  await page.goto(process.env.REVIEW_URL || 'http://127.0.0.1:8011/',{waitUntil:'networkidle'});
  await page.waitForFunction(() => window.trailReviewReady,{timeout:60000});
  assert.equal(await page.locator('#area').inputValue(),'bear-loop');
  assert.match(await page.locator('#detail').textContent(),/Bear Loop/);
  assert.match(await page.locator('#count').textContent(),/1 records shown · 1 included/);
  await mkdir('test-results',{recursive:true});
  await page.waitForFunction(() => window.trailReviewMaps.every((m) => m.loaded()) && window.trailReviewMaps[1].queryRenderedFeatures({layers:['proposed']}).length > 0, null, {timeout:60000});
  assert.equal(await page.evaluate(() => window.trailReviewMaps[0].getLayer('proposed')), undefined);
  assert.ok(await page.evaluate(() => { const b=window.trailReviewMaps[1].getBounds(); return b.contains([-79.83444475,37.95454569]) && b.contains([-79.82201425,37.97105241]); }));
  await page.screenshot({path:'test-results/tnc-usfs-bear-loop.png'});
  await page.locator('#highlight').uncheck();
  await page.locator('#hold-shown').click();
  assert.match(await page.locator('#count').textContent(), /0 included/);
  await page.locator('#include-shown').click();
  await page.locator('#decision').selectOption('exclude');
  assert.match(await page.locator('#count').textContent(),/0 included/);
  await page.locator('#decision').selectOption('include');
  await page.locator('#note').fill('Browser test note');
  await page.locator('#area').selectOption('sandy-gap');
  assert.match(await page.locator('#count').textContent(),/2 included/);
  await page.locator('.record').first().click();
  assert.match(await page.locator('#detail').textContent(),/sources disagree by tens of meters/);
  await page.waitForFunction(() => window.trailReviewMaps.every((m) => m.loaded()) && window.trailReviewMaps[1].queryRenderedFeatures({layers:['proposed']}).length > 0, null, {timeout:60000});
  await page.screenshot({path:'test-results/tnc-usfs-sandy-gap.png'});
  await page.locator('#area').selectOption('bottom-creek-gorge');
  assert.equal(await page.locator('.record').count(),9);
  await page.waitForFunction(() => window.trailReviewMaps.every((m) => m.loaded()) && new Set(window.trailReviewMaps[1].queryRenderedFeatures({layers:['proposed']}).map((f) => f.id)).size === 9, null, {timeout:60000});
  await page.screenshot({path:'test-results/tnc-usfs-bottom-creek.png'});
  await page.locator('#area').selectOption('usfs');
  await page.locator('#status').selectOption('duplicate');
  await page.locator('#search').fill('APPALACHIAN');
  assert.ok(await page.locator('.record').count()>50);
  await page.locator('.record').first().click();
  assert.equal(await page.locator('#decision option[value=include]').count(),0);
  await page.locator('#note').fill('Retain existing Appalachian Trail');
  const pending=page.waitForEvent('download');await page.locator('#export').click();
  const download=await pending, data=JSON.parse(await readFile(await download.path(),'utf8'));
  assert.match(data.review_hash,/^[a-f0-9]{64}$/);
  assert.equal(data.decisions['tnc-virginia:bear-loop:loop-and-approach'],'include');
  assert.equal(data.notes['tnc-virginia:bear-loop:loop-and-approach'],'Browser test note');
  assert.ok(Object.keys(data.decisions).length>1200);
  await page.reload({waitUntil:'networkidle'});await page.waitForFunction(() => window.trailReviewReady);
  assert.equal(await page.locator('#note').inputValue(),'Browser test note');
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth<=window.innerWidth));
  await page.locator('#fit').click();
  await page.waitForFunction(() => window.trailReviewMaps.every((m) => m.loaded()) && window.trailReviewMaps[1].queryRenderedFeatures({layers:['proposed']}).length > 0, null, {timeout:60000});
  await page.screenshot({path:'test-results/tnc-usfs-mobile.png'});
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({passed:true,records:Object.keys(data.decisions).length,checks:'comparison maps, area/status/search filters, official colors, exclusions, held guard, hash-bound export, persistence, mobile'}));
} finally { await browser.close(); }
